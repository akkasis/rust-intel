import type * as T from "@/lib/types";
import { call } from "./transport";

export const api = {
  appInfo: () => call<T.AppInfo>("get_app_info"),
  chooseMode: (mode: T.Mode, timezone?: string) => call<null>("choose_mode", { mode, timezone }),
  updateSettings: (settings: T.AppSettings) => call<T.AppSettings>("update_settings", { settings }),
  parseIdentifier: (input: string) => call<T.ParsedInput>("parse_identifier", { input }),
  search: (input: string) => call<T.SearchOutcome>("search_player", { input }),
  recentSearches: () => call<{ query: string; steam_id: string | null; searched_at: string }[]>("recent_searches"),
  players: (query?: string, favoritesOnly = false) => call<T.Player[]>("list_players", { query, favoritesOnly, limit: 500 }),
  profile: (steamId: string) => call<T.PlayerProfile>("get_player_profile", { steamId }),
  refreshPlayer: (steamId: string) => call<T.Notice[]>("refresh_player", { steamId }),
  searchBattlemetrics: (name: string) => call<T.SearchOutcome["candidates"]>("search_battlemetrics", { name }),
  linkBattlemetrics: (steamId: string, input: string) => call<T.Notice[]>("link_battlemetrics", { steamId, input }),
  unlinkBattlemetrics: (steamId: string) => call<null>("unlink_battlemetrics", { steamId }),
  setFavorite: (steamId: string, favorite: boolean) => call<null>("set_favorite", { steamId, favorite }),
  setNotes: (steamId: string, notes: string | null) => call<null>("set_player_notes", { steamId, notes }),
  deletePlayer: (steamId: string) => call<null>("delete_player", { steamId }),
  purgePlayerHistory: (steamId: string) => call<null>("purge_player_history", { steamId }),
  activity: (steamId: string, range: T.RangeSpec, timezone?: string, serverId?: string | null) =>
    call<T.ActivityReport>("get_activity", { steamId, range, timezone, serverId: serverId ?? null }),
  squads: () => call<T.Squad[]>("list_squads"),
  saveSquad: (s: { id?: number | null; name: string; color: string; notes?: string | null }) =>
    call<number>("save_squad", { id: s.id ?? null, name: s.name, color: s.color, notes: s.notes ?? null }),
  deleteSquad: (id: number) => call<null>("delete_squad", { id }),
  addSquadMember: (id: number, steamId: string, provenance?: string) => call<null>("add_squad_member", { id, steamId, provenance }),
  removeSquadMember: (id: number, steamId: string) => call<null>("remove_squad_member", { id, steamId }),
  squadReport: (id: number, range: T.RangeSpec, timezone?: string) => call<T.SquadReport>("get_squad_report", { id, range, timezone }),
  tracked: () => call<T.TrackedPlayer[]>("list_tracked"),
  setTracking: (steamId: string, enabled: boolean) => call<null>("set_tracking", { steamId, enabled }),
  removeTracking: (steamId: string) => call<null>("remove_tracking", { steamId }),
  setTrackingNotify: (steamId: string, notify: boolean) => call<null>("set_tracking_notify", { steamId, notify }),
  setTrackingPaused: (paused: boolean) => call<null>("set_tracking_paused", { paused }),
  trackerStatus: () => call<T.TrackerStatus>("get_tracker_status"),
  pollNow: () => call<number>("poll_now"),
  events: (f: { steamId?: string; kind?: string; unreadOnly?: boolean; limit?: number; offset?: number } = {}) => call<T.EventRow[]>("list_events", f),
  markEventsRead: (ids?: number[]) => call<null>("mark_events_read", { ids: ids ?? null }),
  bans: () => call<T.BanOverviewRow[]>("get_bans_overview"),
  servers: (query?: string, followedOnly = false) => call<T.Server[]>("list_servers", { query, followedOnly }),
  refreshServers: (query?: string) => call<{ fetched: number; errors: string[]; sources: string[] }>("refresh_servers", { query }),
  setServerFollowed: (id: string, followed: boolean) => call<null>("set_server_followed", { id, followed }),
  population: (id: string, period: string) => call<T.PopulationReport>("get_server_population", { id, period }),
  integrations: () => call<T.IntegrationStatus[]>("get_integrations"),
  setSecret: (key: T.SecretKey, value: string) => call<"os_keyring" | "memory_only">("set_secret", { key, value }),
  clearSecret: (key: T.SecretKey) => call<null>("clear_secret", { key }),
  testIntegration: (provider: string) => call<string>("test_integration", { provider }),
  testNotification: () => call<null>("send_test_notification"),
  exportData: (path: string, format: "json" | "csv_sessions" | "csv_events") => call<number>("export_data", { path, format }),
  importData: (path: string) => call<{ players: number; sessions: number; skipped_demo: number }>("import_data", { path }),
  backup: (path: string) => call<string>("backup_database", { path }),
  restore: (path: string) => call<null>("restore_database", { path }),
  diagnostics: () => call<T.Diagnostics>("get_diagnostics"),
  purgeAll: (confirm: string) => call<null>("purge_all_data", { confirm }),
  dashboard: () => call<T.Dashboard>("get_dashboard"),
};
